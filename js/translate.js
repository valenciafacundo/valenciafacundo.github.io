function cambiarIdioma(idioma) {
  var elementos = Object.keys(textos);
  elementos.forEach(function (elemento) {
    var texto = document.getElementById(elemento + "Text");
    if (texto) {
      texto.textContent = textos[elemento][idioma];
    }
  });

  // Swap the downloadable CV to match the selected language.
  var cv = document.getElementById("cvDownloadLink");
  if (cv) {
    var file =
      idioma === "es"
        ? "CV_Facundo_Valencia_ES.pdf"
        : "CV_Facundo_Valencia_EN.pdf";
    cv.setAttribute("href", "./pdf/" + file);
    cv.setAttribute("download", file);
    cv.setAttribute("data-hover", idioma === "es" ? "Descargar CV" : "Download CV");
  }

  document.documentElement.setAttribute("lang", idioma);
}
